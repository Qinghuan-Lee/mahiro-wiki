"""Build the static site and its article index into dist/."""

import json
import re
from datetime import date
from pathlib import Path
from shutil import copy2, copytree
from string import Template

import yaml
from markdown_it import MarkdownIt


ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "pages"
MODULES = (
    ("articles", "近期文章"),
    ("archive", "归档"),
    ("projects", "我的项目"),
    ("about", "关于网站"),
)
MARKDOWN = MarkdownIt("commonmark", {"html": False})
POST_ID = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def split_post(source):
    if not source.startswith("---\n"):
        return None, source

    front_matter, separator, body = source[4:].partition("\n---\n")
    if not separator:
        raise ValueError("需要用 --- 结束文章信息")

    metadata = yaml.safe_load(front_matter)
    if not isinstance(metadata, dict):
        raise ValueError("文章信息必须是 YAML 字段")
    return metadata, body.lstrip("\n")


def validate_post(slug, metadata, body):
    if not POST_ID.fullmatch(slug):
        raise ValueError("文件名只能使用小写英文字母、数字和连字符")
    if not body.strip():
        raise ValueError("请填写正文")

    post = {"id": slug}
    for key in ("title", "category", "summary"):
        value = metadata.get(key)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{key} 需要填写文字")
        post[key] = value.strip()

    date_text = str(metadata.get("date", ""))
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", date_text):
        raise ValueError("date 需要采用 YYYY-MM-DD 格式")
    post["date"] = date.fromisoformat(date_text).isoformat()

    cover = metadata.get("cover", "assets/covers/desk.svg")
    if not isinstance(cover, str) or not cover.startswith("assets/") or "\\" in cover:
        raise ValueError("cover 需要使用 assets/ 下的相对路径")
    cover_path = (ROOT / cover).resolve()
    if not cover_path.is_relative_to(ROOT / "assets") or not cover_path.is_file():
        raise ValueError(f"找不到封面 {cover}")
    post["cover"] = cover_path.relative_to(ROOT).as_posix()

    for key in ("readingTime", "teaser"):
        if key in metadata:
            if not isinstance(metadata[key], str) or not metadata[key].strip():
                raise ValueError(f"{key} 需要填写文字")
            post[key] = metadata[key].strip()

    for key in ("example", "featured"):
        if key in metadata:
            if not isinstance(metadata[key], bool):
                raise ValueError(f"{key} 需要填写 true 或 false")
            post[key] = metadata[key]

    post["searchText"] = " ".join((post["title"], post["category"], post["summary"], body)).lower()
    post["html"] = MARKDOWN.render(body)
    return post


def read_post(path):
    metadata, body = split_post(path.read_text(encoding="utf-8-sig"))
    if metadata is None:
        return None
    return validate_post(path.stem, metadata, body)


def collect_posts():
    posts = []
    for path in sorted((ROOT / "posts").glob("*.md")):
        try:
            post = read_post(path)
        except (ValueError, yaml.YAMLError) as error:
            raise ValueError(f"{path.relative_to(ROOT)}: {error}") from error
        if post is not None:
            posts.append(post)

    return sorted(posts, key=lambda post: post["date"], reverse=True)


def build_pages(output):
    reader = (PAGES / "reader.html").read_text(encoding="utf-8")
    home = (ROOT / "index.html").read_text(encoding="utf-8")
    (output / "index.html").write_text(home.replace("<!-- article-reader -->", reader), encoding="utf-8")

    layout = Template((PAGES / "module.html").read_text(encoding="utf-8"))
    for module, title in MODULES:
        links = []
        for destination, label in MODULES:
            current = ' aria-current="page"' if destination == module else ""
            links.append(f'<a href="{destination}.html"{current}>{label}</a>')

        filename = f"{module}.html"
        has_articles = module in {"articles", "archive"}
        page = layout.substitute(
            title=title,
            navigation="\n      ".join(links),
            content=(PAGES / filename).read_text(encoding="utf-8").rstrip(),
            script='<script type="module" src="js/main.js"></script>' if has_articles else "",
            reader=reader if has_articles else "",
        )
        (output / filename).write_text(page, encoding="utf-8")


def build():
    try:
        posts = collect_posts()
    except ValueError as error:
        raise SystemExit(str(error)) from error
    output = ROOT / "dist"
    output.mkdir(exist_ok=True)
    build_pages(output)
    site_files = ["style.css"]
    if (ROOT / "CNAME").is_file():
        site_files.append("CNAME")
    for filename in site_files:
        copy2(ROOT / filename, output / filename)
    for directory in ("assets", "js"):
        copytree(ROOT / directory, output / directory, dirs_exist_ok=True)

    post_data = json.dumps(posts, ensure_ascii=False, indent=2)
    (output / "js" / "posts.generated.js").write_text(
        f"// Generated by scripts/build.py.\nexport const posts = {post_data};\n",
        encoding="utf-8",
    )
    print(f"Built {len(posts)} posts into dist/")


if __name__ == "__main__":
    build()
